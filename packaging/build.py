"""Build the Windows exe (PyInstaller) and installer (Inno Setup).

    python packaging/build.py            # exe + installer (installer only if ISCC is found)
    python packaging/build.py --no-installer

Everything version-specific comes from taskpatrol/__init__.py, so bumping
__version__ there is all it takes to get a new side-by-side installable build.
"""

import argparse
import os
import re
import shutil
import subprocess
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
sys.path.insert(0, str(ROOT))

import taskpatrol  # noqa: E402

BUILD = ROOT / "build"
DIST = ROOT / "dist"


def version_tuple(version):
    nums = [int(n) for n in re.findall(r"\d+", version)][:4]
    return tuple(nums + [0] * (4 - len(nums)))


def write_version_info(path):
    v = version_tuple(taskpatrol.__version__)
    exe = f"{taskpatrol.APP_NAME}-{taskpatrol.__version__}.exe"
    path.write_text(f"""# Generated by packaging/build.py
VSVersionInfo(
  ffi=FixedFileInfo(filevers={v}, prodvers={v}, mask=0x3f, flags=0x0, OS=0x40004,
                    fileType=0x1, subtype=0x0, date=(0, 0)),
  kids=[
    StringFileInfo([StringTable('040904B0', [
      StringStruct('CompanyName', {taskpatrol.PUBLISHER!r}),
      StringStruct('FileDescription', 'TaskPatrol process monitor'),
      StringStruct('FileVersion', {taskpatrol.__version__!r}),
      StringStruct('InternalName', {taskpatrol.APP_ID!r}),
      StringStruct('OriginalFilename', {exe!r}),
      StringStruct('ProductName', {taskpatrol.DISPLAY_NAME!r}),
      StringStruct('ProductVersion', {taskpatrol.__version__!r})])]),
    VarFileInfo([VarStruct('Translation', [1033, 1200])])
  ]
)
""", encoding="utf-8")


def make_icon(path):
    """Draw the app icon so the repo doesn't need a binary asset."""
    from PIL import Image, ImageDraw

    size = 256
    img = Image.new("RGBA", (size, size), (0, 0, 0, 0))
    d = ImageDraw.Draw(img)
    d.rounded_rectangle((8, 8, size - 8, size - 8), radius=52, fill=(30, 31, 34, 255),
                        outline=(78, 161, 255, 255), width=10)
    pulse = [(36, 140), (88, 140), (110, 84), (140, 196), (166, 112), (184, 140), (220, 140)]
    d.line(pulse, fill=(87, 171, 90, 255), width=18, joint="curve")
    img.save(path, sizes=[(16, 16), (24, 24), (32, 32), (48, 48), (64, 64), (128, 128), (256, 256)])


def find_iscc():
    found = shutil.which("iscc") or shutil.which("ISCC")
    if found:
        return found
    for base in (os.environ.get("ProgramFiles(x86)"), os.environ.get("ProgramFiles"),
                 os.path.join(os.environ.get("LOCALAPPDATA", ""), "Programs")):
        if base:
            candidate = Path(base) / "Inno Setup 6" / "ISCC.exe"
            if candidate.exists():
                return str(candidate)
    return None


def main():
    parser = argparse.ArgumentParser()
    parser.add_argument("--no-installer", action="store_true")
    args = parser.parse_args()

    name = f"{taskpatrol.APP_NAME}-{taskpatrol.__version__}"
    BUILD.mkdir(exist_ok=True)
    DIST.mkdir(exist_ok=True)
    icon = BUILD / "taskpatrol.ico"
    make_icon(icon)
    version_file = BUILD / "version_info.txt"
    write_version_info(version_file)

    print(f"== Building {name}.exe  (App ID {taskpatrol.APP_ID})")
    subprocess.run([
        sys.executable, "-m", "PyInstaller", "--noconfirm", "--clean", "--onefile", "--windowed",
        "--name", name,
        "--icon", str(icon),
        "--add-data", f"{icon}{os.pathsep}.",
        "--version-file", str(version_file),
        "--distpath", str(DIST),
        "--workpath", str(BUILD / "pyinstaller"),
        "--specpath", str(BUILD),
        str(ROOT / "packaging" / "launcher.py"),
    ], check=True, cwd=ROOT)

    if args.no_installer:
        return
    iscc = find_iscc()
    if not iscc:
        print("!! Inno Setup (ISCC.exe) not found - skipped the installer. Portable exe is in dist/.")
        return
    print(f"== Building installer (AppId {{{taskpatrol.INSTALLER_GUID}}})")
    subprocess.run([
        iscc,
        f"/DAppVersion={taskpatrol.__version__}",
        f"/DAppGuid={taskpatrol.INSTALLER_GUID}",
        f"/DAppUserModelID={taskpatrol.APP_ID}",
        f"/DAppMutex={taskpatrol.MUTEX_NAME.split(chr(92))[-1]}",
        f"/DPublisher={taskpatrol.PUBLISHER}",
        f"/DSourceExe={DIST / (name + '.exe')}",
        f"/DIconFile={icon}",
        f"/O{DIST}",
        str(ROOT / "packaging" / "installer.iss"),
    ], check=True, cwd=ROOT)


if __name__ == "__main__":
    main()
